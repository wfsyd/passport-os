#!/usr/bin/env python3
"""Convert legacy RGB565 Muse avatar frame arrays to palette-indexed RLE.

Each frame becomes (run length, palette index) byte pairs, runs 1..255 long,
summing to 64*64 pixels. The palette holds the exact RGB565 values, so the
conversion is lossless. Identical frames share one data array.

Reproduce from the pre-conversion sources, for example:

    git show aea2c0d:main/apps/muse/muse_avatar_frames.c > /tmp/legacy.c
    python3 tools/gen_muse_avatar_palette.py /tmp/legacy.c \
        main/apps/muse/muse_avatar_frames.c
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

PIXELS = 64 * 64
FRAME_COUNT = 30
PALETTE_LIMIT = 256
FRAME_RE = re.compile(r"static const uint16_t frame_(\d+)\[4096\] = \{(.*?)\};", re.S)
HEX_RE = re.compile(r"0x([0-9a-fA-F]{4})")


def parse_legacy(text: str) -> list[list[int]]:
    frames: dict[int, list[int]] = {}
    for match in FRAME_RE.finditer(text):
        index = int(match.group(1))
        if index in frames:
            raise ValueError(f"duplicate frame_{index}")
        values = [int(v, 16) for v in HEX_RE.findall(match.group(2))]
        if len(values) != PIXELS:
            raise ValueError(f"frame_{index} has {len(values)} pixels")
        frames[index] = values
    if sorted(frames) != list(range(FRAME_COUNT)):
        raise ValueError("expected frame_0 .. frame_29")
    return [frames[i] for i in range(FRAME_COUNT)]


def encode(frames: list[list[int]]) -> tuple[list[int], list[list[tuple[int, int]]]]:
    palette = sorted({colour for frame in frames for colour in frame})
    if len(palette) > PALETTE_LIMIT:
        raise ValueError(f"{len(palette)} colours exceed the 8-bit palette")
    slot = {colour: i for i, colour in enumerate(palette)}
    encoded = []
    for frame in frames:
        runs: list[tuple[int, int]] = []
        at = 0
        while at < PIXELS:
            end = at
            while end < PIXELS and frame[end] == frame[at] and end - at < 255:
                end += 1
            runs.append((end - at, slot[frame[at]]))
            at = end
        encoded.append(runs)
    return palette, encoded


def decode(palette: list[int], runs: list[tuple[int, int]]) -> list[int]:
    pixels: list[int] = []
    for count, index in runs:
        pixels.extend([palette[index]] * count)
    return pixels


def render(legacy_text: str, palette: list[int], encoded: list[list[tuple[int, int]]]) -> str:
    notice = [line for line in legacy_text.splitlines() if line.startswith("//")]
    unique: dict[tuple[tuple[int, int], ...], str] = {}
    frame_symbols = []
    blobs = []
    for runs in encoded:
        key = tuple(runs)
        if key not in unique:
            unique[key] = f"kRle{len(unique)}"
            blobs.append((unique[key], runs))
        frame_symbols.append(unique[key])

    out = list(notice)
    out.append("// Generated by tools/gen_muse_avatar_palette.py. Do not edit by hand.")
    out.append('#include "muse_avatar_frames.h"')
    out.append("")
    out.append(f"static const uint16_t kPalette[{len(palette)}] = {{")
    for i in range(0, len(palette), 16):
        out.append(",".join(f"0x{c:04X}" for c in palette[i:i + 16]) + ",")
    out.append("};")
    out.append("")
    out.append("// Byte pairs (run length, palette index); each frame's runs sum to 4096.")
    for symbol, runs in blobs:
        data = [b for pair in runs for b in pair]
        out.append(f"static const uint8_t {symbol}[{len(data)}] = {{")
        for i in range(0, len(data), 32):
            out.append(",".join(str(b) for b in data[i:i + 32]) + ",")
        out.append("};")
    out.append("")
    out.append(f"static const uint8_t *const kFrames[{FRAME_COUNT}] = {{")
    out.append(", ".join(frame_symbols) + ",")
    out.append("};")
    out.append("")
    out.append("bool muse_avatar_expand_frame(unsigned frame, uint16_t *dst) {")
    out.append(f"    if (frame >= {FRAME_COUNT} || dst == NULL) return false;")
    out.append("    const uint8_t *run = kFrames[frame];")
    out.append("    unsigned at = 0;")
    out.append(f"    while (at < {PIXELS}) {{")
    out.append("        unsigned count = run[0];")
    out.append("        uint16_t colour = kPalette[run[1]];")
    out.append("        run += 2;")
    out.append(f"        for (unsigned i = 0; i < count && at < {PIXELS}; ++i) dst[at++] = colour;")
    out.append("    }")
    out.append("    return true;")
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("legacy", type=Path, help="RGB565 frame_N array source")
    parser.add_argument("output", type=Path, help="palette/RLE C source to write")
    args = parser.parse_args()

    legacy_text = args.legacy.read_text(encoding="utf-8")
    frames = parse_legacy(legacy_text)
    palette, encoded = encode(frames)
    for index, (frame, runs) in enumerate(zip(frames, encoded)):
        if decode(palette, runs) != frame:
            raise SystemExit(f"round-trip mismatch in frame {index}")
    args.output.write_text(render(legacy_text, palette, encoded), encoding="utf-8")
    unique = len({tuple(r) for r in encoded})
    data = sum(2 * len(r) for r in {tuple(r): None for r in encoded})
    print(f"palette {len(palette)} colours, {unique} unique frames, "
          f"RLE data {data} B, legacy {FRAME_COUNT * PIXELS * 2} B")


if __name__ == "__main__":
    main()
